export function getIstanbulClockParts(date: Date = new Date()): {
  hour: number;
  minute: number;
  weekdayIndex: number; // 0 = Sun, 5 = Fri, 6 = Sat
} {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: 'Europe/Istanbul',
    hour: '2-digit',
    minute: '2-digit',
    weekday: 'short',
    hour12: false,
  }).formatToParts(date);

  const hour = Number(parts.find((p) => p.type === 'hour')?.value || 0) % 24;
  const minute = Number(parts.find((p) => p.type === 'minute')?.value || 0);
  const wk = parts.find((p) => p.type === 'weekday')?.value || 'Mon';
  const weekdayMap: Record<string, number> = {
    Sun: 0,
    Mon: 1,
    Tue: 2,
    Wed: 3,
    Thu: 4,
    Fri: 5,
    Sat: 6,
  };
  return { hour, minute, weekdayIndex: weekdayMap[wk] ?? 1 };
}

export function isNight24LineActiveNow(
  line: Night24LineInfo,
  now: Date = new Date()
): { active: boolean; statusText: string } {
  if (line.scheduleType === '24/7') {
    const { hour } = getIstanbulClockParts(now);
    const isOvernight = hour >= 0 && hour < 6;
    return {
      active: true,
      statusText: isOvernight ? 'Gece Seferinde Aktif' : 'Şu An Aktif (7/24)',
    };
  }

  const { hour, weekdayIndex } = getIstanbulClockParts(now);
  const isOvernightWindow = hour >= 0 && hour < 6;

  if (!isOvernightWindow) {
    return {
      active: true,
      statusText: 'Şu An Aktif (Gündüz Seferi)',
    };
  }

  // Overnight 00:00–05:59: Weekend night metro runs on Saturday morning (after Fri night) and Sunday morning (after Sat night)
  const isWeekendOvernight = weekdayIndex === 6 || weekdayIndex === 0;
  if (isWeekendOvernight) {
    return {
      active: true,
      statusText: 'Gece Metrosu Aktif',
    };
  }

  return {
    active: false,
    statusText: 'Hafta İçi Gece Kapalı (06:00’da Açılır)',
  };
}
